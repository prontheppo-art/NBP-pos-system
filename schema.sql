-- TABLE: public.customer_types
CREATE TABLE IF NOT EXISTS public.customer_types (
    customer_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT
);

-- TABLE: public.customers
CREATE TABLE IF NOT EXISTS public.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT
);

-- TABLE: public.food_groups
CREATE TABLE IF NOT EXISTS public.food_groups (
    food_group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT
);

-- TABLE: public.foods
CREATE TABLE IF NOT EXISTS public.foods (
    food_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    food_group_id BIGINT,
    price_1 BIGINT,
    price_2 BIGINT,
    price_3 BIGINT
);

-- TABLE: public.locations
CREATE TABLE IF NOT EXISTS public.locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT
);

-- TABLE: public.orders
CREATE TABLE IF NOT EXISTS public.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ,
    total_price BIGINT,
    total_qty BIGINT,
    items JSONB,
    name_phone TEXT,
    customer_type_id BIGINT,
    note TEXT,
    location_id TEXT,
    zone_id TEXT,
    delivery_fee BIGINT,
    subtotal BIGINT,
    customer_id BIGINT
);

-- TABLE: public.zones
CREATE TABLE IF NOT EXISTS public.zones (
    zone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    location_id BIGINT
);
